function buildAssessmentDetail(
  assessment: any,
  studentCount: number,
  maxScore: number,
  timeMinutes: number,
): any {
  const students = STUDENT_POOL.slice(0, studentCount);
  const now = Date.now();
  const day = (d: number) => new Date(now - d * 86_400_000).toISOString();

  const invitations = students.map((s, i) => ({
    id: `inv_${assessment.id}_${i + 1}`,
    assessment_id: assessment.id,
    email: s.email,
    name: s.name,
    status: s.score != null ? 'completed' : 'pending',
    invited_at: day(7 - i),
    sent_at: day(7 - i),
  }));

  const attempts: any[] = [];
  students.forEach((s, i) => {
    if (s.score == null) return;
    // Scale score from 0-100 base to actual maxScore
    const scaledScore = Math.round((s.score / 100) * maxScore);
    const correctRatio = s.score / 100;
    // Cap demo question count at 10 so review screen stays readable
    const totalQ = Math.min(assessment.question_count || 20, 10);
    const correctCount = Math.round(totalQ * correctRatio);
    const wrongCount = Math.max(0, totalQ - correctCount - (s.score < 50 ? 1 : 0));
    const unansweredCount = totalQ - correctCount - wrongCount;
    const duration = s.duration ?? timeMinutes - 10;

    const startedAt = day(7 - i);
    const submittedAt = new Date(new Date(startedAt).getTime() + duration * 60_000).toISOString();

    // Build question-by-question review using the question bank pool
    const questions = SAMPLE_EVAL_QUESTIONS.slice(0, totalQ).map((q, qi) => {
      let isCorrect = false;
      let studentAnswer: any = null;
      if (qi < correctCount) {
        isCorrect = true;
        studentAnswer = q.correct_answer;
      } else if (qi < correctCount + wrongCount) {
        // Pick a wrong option that isn't the correct one
        const wrong = (q.options as string[]).find(o => o !== q.correct_answer) ?? null;
        studentAnswer = wrong;
        isCorrect = false;
      } else {
        // unanswered
        studentAnswer = null;
        isCorrect = false;
      }
      return {
        id: `q_${assessment.id}_${i + 1}_${qi + 1}`,
        text: q.text,
        question_text: q.text,
        type: q.type,
        question_type: q.type,
        options: q.options,
        correct_answer: q.correct_answer,
        student_answer: studentAnswer,
        is_correct: isCorrect,
        explanation: q.explanation,
        marks: q.marks,
        points: q.points,
        subject: q.subject,
        chapter: q.chapter,
        difficulty: q.difficulty,
        order_index: qi + 1,
      };
    });

    attempts.push({
      id: `att_${assessment.id}_${i + 1}`,
      assessment_id: assessment.id,
      invitation_id: invitations[i].id,
      student_id: invitations[i].id,
      student_name: s.name,
      student_email: s.email,
      assessment_title: assessment.title,
      status: 'submitted',
      score: scaledScore,
      max_score: maxScore,
      percentage: s.score,
      correct_count: correctCount,
      wrong_count: wrongCount,
      unanswered_count: unansweredCount,
      started_at: startedAt,
      submitted_at: submittedAt,
      negative_marking: assessment.negative_marking,
      negative_mark_value: assessment.negative_mark_value,
      questions,
      attempt_metadata: {
        tab_violations: s.violations ?? 0,
        submit_reason: s.submitReason ?? 'manual',
        auto_submitted: !!s.submitReason && s.submitReason !== 'manual',
      },
    });
  });

  return { ...assessment, invitations, attempts };
}

// Built lazily from SAMPLE_EVAL_ASSESSMENTS so changes there propagate here.
export const SAMPLE_EVAL_ASSESSMENT_DETAILS: Record<string, any> = (() => {
  const out: Record<string, any> = {};
  for (const asm of SAMPLE_EVAL_ASSESSMENTS) {
    const stats = SAMPLE_EVAL_INVITATION_STATS[asm.id];
    const invited = stats?.invited ?? 8;
    out[asm.id] = buildAssessmentDetail(asm, invited, asm.max_score, asm.time_limit);
  }
  return out;
})();

